SELECT
    workspace_binding_id,
    application_id,
    external_user_id,
    workspace_key,
    external_user_hash,
    workspace_root,
    is_active,
    last_used_at,
    created_at,
    updated_at,
    lifecycle_state,
    archived_at
FROM workspace_bindings
WHERE workspace_binding_id = $1
LIMIT 1;
