use sea_orm::sea_query::{IndexCreateStatement, PostgresQueryBuilder, TableCreateStatement};

fn table_sql(table: TableCreateStatement) -> String {
    table.to_string(PostgresQueryBuilder)
}

fn index_sql(index: IndexCreateStatement) -> String {
    index.to_string(PostgresQueryBuilder)
}

#[test]
fn native_tables_declare_deployed_types_defaults_and_checks() {
    let users = table_sql(super::user::table());
    assert!(
        users.contains("\"user_id\" bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY"),
        "{users}"
    );
    assert!(users.contains("\"login_name\" text NOT NULL"), "{users}");
    assert!(users.contains("\"workspace_root\" text"), "{users}");
    assert!(
        users.contains("\"is_admin\" bool NOT NULL DEFAULT FALSE"),
        "{users}"
    );
    assert!(
        users
            .contains("\"created_at\" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP"),
        "{users}"
    );

    let tokens = table_sql(super::mcp_token::table());
    assert!(
        tokens.contains("\"scopes\" text[] NOT NULL DEFAULT (ARRAY['workspace.read', 'workspace.search', 'workspace.shell', 'workspace.patch']::TEXT[])"),
        "{tokens}"
    );
    assert!(
        tokens.contains("\"network_enabled\" bool NOT NULL DEFAULT TRUE"),
        "{tokens}"
    );
    assert!(tokens.contains("\"token_hash\" text NOT NULL"), "{tokens}");

    let applications = table_sql(super::application::table());
    assert!(
        applications.contains("\"default_scopes\" text[] NOT NULL DEFAULT (ARRAY['workspace.read', 'workspace.search', 'workspace.shell', 'workspace.patch']::TEXT[])"),
        "{applications}"
    );
    assert!(
        applications.contains("\"workspace_template\" text"),
        "{applications}"
    );
    assert!(
        applications.contains("\"is_active\" bool NOT NULL DEFAULT TRUE"),
        "{applications}"
    );

    let application_tokens = table_sql(super::application_token::table());
    assert!(
        application_tokens.contains("\"application_id\" bigint NOT NULL"),
        "{application_tokens}"
    );
    assert!(
        application_tokens.contains("\"scopes\" text[] NOT NULL"),
        "{application_tokens}"
    );

    let audit = table_sql(super::audit_log::table());
    assert!(
        audit.contains("\"payload\" jsonb NOT NULL DEFAULT ('{}'::JSONB)"),
        "{audit}"
    );
    assert!(audit.contains("\"action\" text NOT NULL"), "{audit}");
    assert!(
        audit
            .contains("\"created_at\" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP"),
        "{audit}"
    );

    let managers = table_sql(super::runner_manager::table());
    assert!(
        managers.contains("\"image\" text NOT NULL DEFAULT 'desk-foreman-workspace-runner:local'"),
        "{managers}"
    );
    assert!(
        managers.contains("\"max_sessions\" bigint NOT NULL DEFAULT 32"),
        "{managers}"
    );
    assert!(
        managers.contains("\"status\" text NOT NULL DEFAULT 'pending'"),
        "{managers}"
    );

    let runners = table_sql(super::workspace_runner::table());
    assert!(
        runners.contains("CONSTRAINT \"workspace_runners_owner_check\" CHECK"),
        "{runners}"
    );
    assert!(
        runners.contains("\"runtime\" text NOT NULL DEFAULT 'docker'"),
        "{runners}"
    );
    assert!(
        runners.contains("\"owner_principal_digest\" text"),
        "{runners}"
    );
    assert!(
        runners.contains("owner_principal_digest ~ '^[0-9a-f]{64}$'"),
        "{runners}"
    );

    let sessions = table_sql(super::web_session::table());
    assert!(
        sessions.contains("\"session_id\" uuid NOT NULL PRIMARY KEY"),
        "{sessions}"
    );
    assert!(
        sessions.contains(
            "\"last_seen_at\" timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP"
        ),
        "{sessions}"
    );
}

#[test]
fn native_indexes_declare_unique_partial_and_composite_structures() {
    let user_indexes: Vec<String> = super::user::indexes().into_iter().map(index_sql).collect();
    assert!(
        user_indexes.iter().any(|sql| {
            sql.contains("CREATE UNIQUE INDEX IF NOT EXISTS \"users_login_name_active_key\"")
                && sql.contains("(\"login_name\")")
                && sql.contains("WHERE \"users\".\"deleted_at\" IS NULL")
        }),
        "{user_indexes:?}"
    );
    assert!(
        user_indexes.iter().any(|sql| {
            sql.contains("CREATE UNIQUE INDEX IF NOT EXISTS \"users_email_active_key\"")
                && sql.contains("(\"email\")")
        }),
        "{user_indexes:?}"
    );

    let runner_indexes: Vec<String> = super::workspace_runner::indexes()
        .into_iter()
        .map(index_sql)
        .collect();
    assert!(
        runner_indexes.iter().any(|sql| {
            sql.contains(
                "CREATE UNIQUE INDEX IF NOT EXISTS \"workspace_runners_manager_container_idx\"",
            ) && sql.contains("(\"runner_manager_id\", \"container_name\")")
        }),
        "{runner_indexes:?}"
    );
    assert!(
        runner_indexes.iter().any(|sql| {
            sql.contains("CREATE UNIQUE INDEX IF NOT EXISTS \"workspace_runners_manager_principal_owner_idx\"")
                && sql.contains("WHERE \"workspace_runners\".\"owner_kind\" = 'application_principal'")
        }),
        "{runner_indexes:?}"
    );
    assert_eq!(runner_indexes.len(), 6);

    let audit_indexes: Vec<String> = super::audit_log::indexes()
        .into_iter()
        .map(index_sql)
        .collect();
    assert!(
        audit_indexes.iter().any(|sql| {
            sql.contains("CREATE INDEX IF NOT EXISTS \"audit_log_created_at_idx\"")
                && sql.contains("(\"created_at\" DESC)")
        }),
        "{audit_indexes:?}"
    );

    assert_eq!(super::application::indexes().len(), 0);
    assert_eq!(super::application_token::indexes().len(), 1);
    assert_eq!(super::mcp_token::indexes().len(), 1);
    assert_eq!(super::runner_manager::indexes().len(), 2);
    assert_eq!(super::web_session::indexes().len(), 2);
}

#[test]
fn native_unique_constraints_are_named_table_constraints() {
    for (sql, constraint, column) in [
        (
            table_sql(super::application::table()),
            "applications_name_key",
            "name",
        ),
        (
            table_sql(super::application_token::table()),
            "application_tokens_token_hash_key",
            "token_hash",
        ),
        (
            table_sql(super::mcp_token::table()),
            "mcp_tokens_token_hash_key",
            "token_hash",
        ),
        (
            table_sql(super::runner_manager::table()),
            "runner_managers_access_token_hash_key",
            "access_token_hash",
        ),
    ] {
        assert!(
            sql.contains(&format!(
                "CONSTRAINT \"{constraint}\" UNIQUE (\"{column}\")"
            )),
            "{sql}"
        );
        assert!(
            !sql.contains(&format!("CREATE UNIQUE INDEX \"{constraint}\"")),
            "{sql}"
        );
    }

    for (name, indexes) in [
        ("applications_name_key", super::application::indexes()),
        (
            "application_tokens_token_hash_key",
            super::application_token::indexes(),
        ),
        ("mcp_tokens_token_hash_key", super::mcp_token::indexes()),
        (
            "runner_managers_access_token_hash_key",
            super::runner_manager::indexes(),
        ),
    ] {
        assert!(
            !indexes
                .into_iter()
                .map(index_sql)
                .any(|sql| sql.contains(&format!("\"{name}\""))),
            "{name} must be a table constraint, not a standalone index"
        );
    }
}
